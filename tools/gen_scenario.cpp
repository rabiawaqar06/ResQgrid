// File:       tools/gen_scenario.cpp
// Owner:      Rabia
// Purpose:    Seeded scenario generator for the performance runs. Writes a
//             valid scenario file in our exact input format:
//               - a connected grid of locations plus random diagonal roads,
//                 some roads BLOCKED (never a road the grid needs to stay connected),
//               - chargers, hospitals, depots, one command post, buildings, junctions,
//               - robots of every capability, requests spread over time,
//               - events of every type (BLOCK/UNBLOCK, STATION_DOWN/UP,
//                 SET_URGENCY, ROBOT_OFFLINE/ONLINE).
//             Same arguments -> same file (own random generator, no rand()).
// Usage:      gen_scenario <locations> <seed> <out_file> [max_steps]
// Build:      cmake builds it as target gen_scenario, or
//             g++ -std=c++17 tools/gen_scenario.cpp -o gen_scenario
#include <iostream>
#include <fstream>
#include <cstdlib>

using namespace std;

static unsigned long long g_state = 1;

// Simple linear congruential generator (deterministic on every platform).
static int nextRand(int n) {
    g_state = (g_state * 6364136223846793005ULL + 1442695040888963407ULL);
    return (int)((g_state >> 33) % (unsigned long long)n);
}

static int between(int lo, int hi) {
    return lo + nextRand(hi - lo + 1);
}

int main(int argc, char* argv[]) {
    if (argc < 4) {
        cerr << "Usage: " << argv[0] << " <locations> <seed> <out_file> [max_steps]\n";
        return 1;
    }
    int n = atoi(argv[1]);
    int seed = atoi(argv[2]);
    int maxSteps = 600;
    if (argc >= 5) {
        maxSteps = atoi(argv[4]);
    }
    if (n < 10 || maxSteps < 10) {
        cerr << "need at least 10 locations and 10 steps\n";
        return 1;
    }
    g_state = (unsigned long long)seed * 7919ULL + 17ULL;

    ofstream out(argv[3]);
    if (!out.is_open()) {
        cerr << "cannot open " << argv[3] << "\n";
        return 1;
    }

    // ---- grid size ----
    int cols = 1;
    while (cols * cols < n) {
        cols++;
    }

    // ---- location types ----
    int* type = new int[n];          // 0 JUNCTION 1 BUILDING 2 HOSPITAL 3 DEPOT 4 CHARGING 5 COMMAND
    int chargers = 0;
    for (int i = 0; i < n; i++) {
        int r = nextRand(100);
        if (i % 12 == 5) {
            type[i] = 4;
            chargers++;
        } else if (r < 40) {
            type[i] = 1;
        } else if (r < 47) {
            type[i] = 2;
        } else if (r < 52) {
            type[i] = 3;
        } else {
            type[i] = 0;
        }
    }
    type[0] = 5;
    const char* typeName[6] = { "JUNCTION", "BUILDING", "HOSPITAL", "DEPOT", "CHARGING", "COMMAND" };
    const char* typeShort[6] = { "Junction", "Building", "Hospital", "Depot", "Charger", "Command" };

    // ---- connections: grid (right + down) and diagonals ----
    int maxConn = 3 * n;
    int* ca = new int[maxConn];
    int* cb = new int[maxConn];
    int* cost = new int[maxConn];
    bool* blocked = new bool[maxConn];
    bool* needed = new bool[maxConn];   // in the spanning tree: never blocked
    int m = 0;
    for (int i = 0; i < n; i++) {
        int col = i % cols;
        if (col + 1 < cols && i + 1 < n) {          // right: every row stays a path
            ca[m] = i; cb[m] = i + 1; cost[m] = between(2, 12);
            blocked[m] = false; needed[m] = true; m++;
        }
        if (i + cols < n) {                          // down: column 0 joins the rows
            ca[m] = i; cb[m] = i + cols; cost[m] = between(2, 12);
            blocked[m] = false; needed[m] = (col == 0); m++;
        }
        if (col + 1 < cols && i + cols + 1 < n && nextRand(100) < 15) {   // diagonal shortcut
            ca[m] = i; cb[m] = i + cols + 1; cost[m] = between(3, 12);
            blocked[m] = false; needed[m] = false; m++;
        }
    }
    // block about 4% of the roads the grid does not need (the last, shorter row
    // still connects through column 0)
    for (int c = 0; c < m; c++) {
        if (!needed[c] && nextRand(100) < 4) {
            blocked[c] = true;
        }
    }

    // ---- robots ----
    int robots = n / 5;
    if (robots < 10) {
        robots = 10;
    }
    int requests = n + n / 4;
    int events = n / 2;
    if (events < 14) {
        events = 14;
    }

    const char* capName[5] = { "MEDICAL", "FIRE", "SUPPLY", "SEARCH", "GENERAL" };
    const char* catName[4] = { "MEDICAL", "FIRE", "SUPPLY", "SEARCH" };

    // ---- header and params ----
    out << "# Generated by tools/gen_scenario " << n << " " << seed << " (max_steps " << maxSteps << ")\n";
    out << "# Connected grid of " << n << " locations with diagonal shortcuts; "
        << "blocked roads are never needed for connectivity.\n";
    out << "SCENARIO perf_" << n << "\n\n";
    out << "PARAM max_steps " << maxSteps << "\n";
    out << "PARAM speed 2\n";
    out << "PARAM battery_per_cost_unit 1\n";
    out << "PARAM battery_per_work_step 1\n";
    out << "PARAM recharge_per_step 10\n";
    out << "PARAM aging_interval 50\n";
    out << "PARAM low_battery_percent 30\n\n";

    out << "LOCATIONS " << n << "\n";
    for (int i = 0; i < n; i++) {
        out << (i + 1) << " " << typeShort[type[i]] << "_" << (i + 1) << " " << typeName[type[i]] << "\n";
    }

    out << "\nCONNECTIONS " << m << "\n";
    for (int c = 0; c < m; c++) {
        out << (c + 1) << " " << (ca[c] + 1) << " " << (cb[c] + 1) << " " << cost[c] << " "
            << (blocked[c] ? "BLOCKED" : "OPEN") << "\n";
    }

    out << "\nROBOTS " << robots << "\n";
    for (int r = 0; r < robots; r++) {
        int maxBat = between(120, 200);
        int start = nextRand(n);
        int bat = maxBat;
        if (r % 5 == 0) {
            bat = maxBat / 2;            // some robots start half charged
        }
        out << (r + 1) << " " << (start + 1) << " " << capName[r % 5] << " " << maxBat << " " << bat << "\n";
    }

    out << "\nREQUESTS " << requests << "\n";
    int lastReport = maxSteps * 6 / 10;
    for (int q = 0; q < requests; q++) {
        int t = (int)((long long)q * lastReport / requests);    // spread over time, in order
        int loc = nextRand(n);
        if (type[loc] == 4) {
            loc = (loc + 1) % n;
        }
        out << (q + 1) << " " << t << " " << (loc + 1) << " " << catName[nextRand(4)] << " "
            << between(1, 5) << " " << between(1, 5) << "\n";
    }

    // ---- events: cycle through all 7 types ----
    out << "\nEVENTS " << events << "\n";
    int* blockedByEvent = new int[events];
    int blockedCount = 0;
    int* offlineRobot = new int[events];
    int offlineCount = 0;
    for (int e = 0; e < events; e++) {
        int t = 1 + (int)((long long)e * (lastReport - 1) / events);
        int kind = e % 7;
        if (kind == 0) {                                  // BLOCK a road that is not needed
            int c = nextRand(m);
            while (needed[c]) {
                c = (c + 1) % m;
            }
            blockedByEvent[blockedCount] = c;
            blockedCount++;
            out << t << " BLOCK " << (c + 1) << "\n";
        } else if (kind == 1) {                           // UNBLOCK the oldest road blocked by an event
            int c = 0;
            if (blockedCount > 0) {
                c = blockedByEvent[0];
                for (int k = 1; k < blockedCount; k++) {
                    blockedByEvent[k - 1] = blockedByEvent[k];
                }
                blockedCount--;
            }
            out << t << " UNBLOCK " << (c + 1) << "\n";
        } else if (kind == 2 || kind == 3) {              // STATION_DOWN then STATION_UP on a charger
            int loc = 5 + 12 * nextRand(chargers);
            if (loc >= n) {
                loc = 5;
            }
            out << t << (kind == 2 ? " STATION_DOWN " : " STATION_UP ") << (loc + 1) << "\n";
        } else if (kind == 4) {                           // SET_URGENCY on an earlier request
            int maxReq = (int)((long long)t * requests / lastReport) + 1;
            if (maxReq > requests) {
                maxReq = requests;
            }
            out << t << " SET_URGENCY " << (nextRand(maxReq) + 1) << " " << between(1, 5) << "\n";
        } else if (kind == 5) {                           // ROBOT_OFFLINE
            int r = nextRand(robots);
            offlineRobot[offlineCount] = r;
            offlineCount++;
            out << t << " ROBOT_OFFLINE " << (r + 1) << "\n";
        } else {                                          // ROBOT_ONLINE the robot that went offline
            int r = 0;
            if (offlineCount > 0) {
                r = offlineRobot[offlineCount - 1];
                offlineCount--;
            }
            out << t << " ROBOT_ONLINE " << (r + 1) << "\n";
        }
    }
    out << "\nEND\n";

    delete[] type;
    delete[] ca;
    delete[] cb;
    delete[] cost;
    delete[] blocked;
    delete[] needed;
    delete[] blockedByEvent;
    delete[] offlineRobot;

    cout << "wrote " << argv[3] << ": " << n << " locations, " << m << " connections, " << robots
         << " robots, " << requests << " requests, " << events << " events, max_steps " << maxSteps << "\n";
    return 0;
}
